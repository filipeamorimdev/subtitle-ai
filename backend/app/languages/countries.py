COUNTRIES_BY_CODE: dict[str, Country] = {country.code: country for country in COUNTRIES}


def country_name(code: str) -> str:
    upper = code.upper()
    country = COUNTRIES_BY_CODE.get(upper)
    return country.name if country else upper


def country_languages(code: str) -> tuple[str, ...]:
    country = COUNTRIES_BY_CODE.get(code.upper())
    return country.languages if country else ()


def flag_emoji(region: str | None) -> str:
    """Regional-indicator flag for an ISO 3166-1 alpha-2 code."""
    if not region:
        return "🏳️"
    letters = region.strip().upper()
    if len(letters) != 2 or not letters.isalpha():
        return "🏳️"
    return "".join(chr(0x1F1E6 + ord(char) - ord("A")) for char in letters)
