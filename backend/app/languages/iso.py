def is_iso_639_1(code: str) -> bool:
    return code.lower() in ISO_639_1


def is_iso_3166_1(code: str) -> bool:
    return code.upper() in ISO_3166_1


def language_name(code: str) -> str:
    return ISO_639_1.get(code.lower(), code)

def region_name(code: str) -> str:
    from app.languages.countries import country_name

    return country_name(code)
